#Typecasting = the process of converting a variable from one data type to another
#              str(), int(), float(), bool()


name = "James Donut"
age = 20
gpa = 3.5
is_student = True

gpa = int(gpa)

print(gpa)

age = float(age)

print(age)

is_student = str(is_student)

print(is_student)

name = bool(name)

print(name)